// función que resuelve el problema
int resolver(int datos, int md) {
    int n = datos/ 10;
    int mod = datos%10;

    if(n == 0) return md+datos;
    
    
    return resolver(n,(md+mod)*10);
}

// Resuelve un caso de prueba, leyendo de la entrada la
// configuración, y escribiendo la respuesta
bool resuelveCaso() {
    // leer los datos de la entrada
    int n;
    cin >> n;
    if (n == 0)
        return false;
    
    int p =0;
    int sol = resolver(n,p);
    
    // escribir sol
    cout << sol <<endl;
    
    return true;
    
}

